# ============================================================
# 优先级 / 边界专项
# ============================================================
def test_seasoning_powder_beats_spicy():
    """「辣椒粉」→ 粉末调料（长关键词优先），而非辣味调料。"""
    assert classify_seasoning("辣椒粉") == "粉末调料"


def test_seasoning_spicy_oil_beats_oil():
    """「辣椒油」→ 辣味调料（长关键词优先），而非油脂。"""
    assert classify_seasoning("辣椒油") == "辣味调料"


def test_recipe_noodle_beats_soup():
    """「西红柿汤面」→ 面食（汤面 2 字 > 汤 1 字），而非汤羹。"""
    assert classify_recipe("西红柿汤面") == "面食"


def test_recipe_dessert_beats_quick():
    """「简单快手蛋糕」→ 甜点（同长关键词时表序靠前优先），而非快手菜。"""
    assert classify_recipe("简单快手蛋糕") == "甜点"


# ============================================================
# 显式 category 优先（JSON 直入）
# ============================================================
@pytest.mark.parametrize("title,explicit,expected", [
    # 显式分类在规范清单内 → 直接采用
    ("红烧肉", "汤羹", "汤羹"),
    ("红烧肉", "默认", "默认"),
    (" 甜点 ", "甜点", "甜点"),   # 显式分类会 normalize
    ("红烧肉", 5, "炖菜"),        # 非字符串显式值不崩溃 → 回落标题规则
    ("红烧肉", True, "炖菜"),     # 布尔值同样安全回落
    # 显式分类非法/拼错 → 回落标题规则
    ("红烧肉", "烫羹", "炖菜"),   # 非法分类 → 按标题 红烧→炖菜
    ("番茄炒蛋", "汤类", "家常菜"),
    ("西红柿炒鸡蛋", "", "家常菜"),  # 空显式 → 标题规则
])
def test_resolve_recipe_category(title, explicit, expected):
    assert resolve_recipe_category(title, explicit) == expected


def test_resolve_recipe_category_none_explicit():
    """显式分类缺省时完全等价于标题规则。"""
    assert resolve_recipe_category("凉拌黄瓜", None) == classify_recipe("凉拌黄瓜")


def test_seasoning_exclude_guard():
    """「酱牛肉」含「酱」但不归酱料（exclude 保护），归类器返回 None。"""
    assert classify_seasoning("酱牛肉") is None


def test_ingredient_seasoning_guard():
    """classify_ingredient 对调料名（含已知调料集合兜底）返回 None。"""
    assert classify_ingredient("姜") is None
    assert classify_ingredient("大蒜") is None
    assert classify_ingredient("料酒") is None
    # 已知调料集合兜底：静态词典外的调料名也可被识别
    assert classify_ingredient("十三香", known_seasonings={"十三香"}) is None
